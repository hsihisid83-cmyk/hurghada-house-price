score = 0
for i, item in enumerate(questions):
    st.markdown(f"**{i+1}. [{item['sec']}]** {item['q']}")
    choice = st.radio("اختار:", item['opts'], key=i, index=None)
    if choice:
        if choice == item['ans']:
            st.success("✅ صح")
            score += 1
        else:
            st.error(f"❌ الصح: {item['ans']}")
    st.write("---")

if st.button("احسب النتيجة النهائية 🔥"):
    st.balloons()
    st.metric("نتيجتك", f"{score} من {len(questions)}")
    if score == len(questions):
        st.success("جامد! انت مقفل الـ PDF كله 💪")
